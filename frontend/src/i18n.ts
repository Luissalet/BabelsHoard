export type Key = keyof typeof dict.en;

export function detectLang(): Lang {
  try {
    const stored = localStorage.getItem("babel.lang");
    if (stored === "en" || stored === "es") return stored;
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith("es") ? "es" : "en";
}

/** Translated label of an entry kind ("method" -> "método"); unknown kinds as-is. */
export function kindLabel(lang: Lang, kind: string): string {
  const key = `kind_${kind}` as Key;
  return key in dict.en ? t(lang, key) : kind;
}

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}
